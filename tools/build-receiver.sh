#!/usr/bin/env bash
# Build the receiver into a .vpk.
#
#   ./tools/build-receiver.sh                 slot A: FVTA00001, port 1341
#   ./tools/build-receiver.sh --slot b        slot B: FVTA00005, port 1341
#   ./tools/build-receiver.sh --scratch       a throwaway: FVTA00004, port 1342
#
#   --title-id ID   override the slot
#   --port N        override the port
#
# ## Two slots
#
# A running title cannot write its own directory, so a receiver can never
# install itself. It installs the *other* receiver and hands the console over.
# A and B take turns, and the one that is not running is the rescue: a whole
# working install rather than a saved eboot. tools/selfupdate-receiver.sh picks
# the slot; you rarely pass --slot by hand.
#
# Both slots build for port 1341. Only one of them runs at a time, so there is
# nothing to collide with, and every host tool keeps talking to one number.
#
# The slot is *not* compiled in. The receiver reads its own title id at startup
# (read_self_titleid in receiver/src/receiver_dev.c), so A and B are the same
# eboot.bin and switching slots regenerates param.sfo rather than relinking the
# engine. --slot decides what goes in the package, not what goes in the binary.
#
# The receiver is an ordinary Flutter-Vita application -- same template, same
# build script, same snapshot -- plus one translation unit that owns the port
# and the commands, and minus the crash supervisor.
#
# --scratch exists because replacing FVTA00001 in place replaces the only way to
# install anything. A scratch receiver installs beside the working one, on its
# own port, and is driven with `./tools/deploy.sh --receiver-port 1342`.
#
# tools/install-vpk.sh registers the id as part of installing, so the slot does
# not have to exist first.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"

ENGINE="$ROOT/out/artifacts/receiver-engine"
PIN="$ROOT/receiver/engine-pin.txt"
# FVTA00001 since 2026-08-31. It was FVTA00003 for as long as the receiver had
# to be installed by VitaShell, which meant living in whichever slot someone
# had already created by hand. The receiver registers its own title id now, so
# the number is a choice rather than an inheritance.
TITLE_ID="FVTA00001"
PORT=1341
NAME="Flutter Vita Receiver A"

while [ $# -gt 0 ]; do
  case "$1" in
    --slot)
      case "$2" in
        a|A) TITLE_ID="FVTA00001"; NAME="Flutter Vita Receiver A" ;;
        b|B) TITLE_ID="FVTA00005"; NAME="Flutter Vita Receiver B" ;;
        *) echo "--slot takes a or b" >&2; exit 2 ;;
      esac
      shift 2 ;;
    --scratch)  TITLE_ID="FVTA00004"; PORT=1342; NAME="Flutter Receiver (scratch)"; shift ;;
    --title-id) TITLE_ID="$2"; shift 2 ;;
    --port)     PORT="$2"; shift 2 ;;
    -h|--help)  sed -n '2,35p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

# ------------------------------------------------------------- the pin check
#
# ADR-0016 decision 2: the receiver links a pinned engine, not the one under
# development, so that a broken engine can cost you your app and never your
# ability to replace it. The sha is what makes that mean anything -- without
# it "the pinned tree" is just a directory someone could have rsynced over.
[ -f "$PIN" ] || {
  echo "No $PIN. Run tools/pin-receiver-engine.sh." >&2; exit 1; }
[ -d "$ENGINE" ] || {
  echo "No pinned engine at $ENGINE." >&2
  echo "  It is gitignored, so a fresh checkout has to pin one:" >&2
  echo "    ./tools/pin-receiver-engine.sh --reason 'restoring the pin'" >&2
  echo "  Check it produces the sha in $PIN before trusting the result." >&2
  exit 1
}

WANT="$(grep -m1 '^archive_sha256 ' "$PIN" | awk '{print $2}')"
HAVE="$(shasum -a 256 "$ENGINE/lib/libflutter_engine_vita.a" | cut -d' ' -f1)"
if [ "$WANT" != "$HAVE" ]; then
  echo "!! the pinned engine does not match the pin." >&2
  echo "   $PIN says  $WANT" >&2
  echo "   $ENGINE has $HAVE" >&2
  echo >&2
  echo "   Either the tree was overwritten, or the pin should be bumped." >&2
  echo "   Bumping is deliberate: ./tools/pin-receiver-engine.sh --reason '...'" >&2
  exit 1
fi
echo "==> pinned engine $(grep -m1 '^flutter ' "$PIN" | awk '{print $2}') ($(echo "$HAVE" | cut -c1-12))"

# --------------------------------------------------------------- build_info
#
# Generated rather than committed: three of the four values are properties of
# the engine artifact, and a committed copy is a copy that can disagree with
# the thing it describes. The fourth is the receiver's own version, which comes
# from its pubspec.
key() { grep -m1 "^$1 " "$PIN" | awk '{print $2}'; }
VERSION="$(grep -m1 '^version:' "$ROOT/receiver/app/pubspec.yaml" | sed 's/^version: *//')"
cat > "$ROOT/receiver/app/lib/build_info.dart" <<EOF
// GENERATED by tools/build-receiver.sh. Do not edit, and do not commit.
//
// What the screen's bottom line reports. These describe the *pinned* engine
// (ADR-0016 decision 2), which is deliberately not the engine in the tree.
const String kReceiverVersion = '$VERSION';
const String kFlutterVersion = '$(key flutter)';
const String kEngineRevision = '$(key engine)';
const String kFrameworkRevision = '$(key framework_rev)';
EOF

echo "==> $NAME [$TITLE_ID] on port $PORT"
exec "$HERE/build-vita-app.sh" "$ROOT/receiver/app" \
  --engine "$ENGINE" \
  --title-id "$TITLE_ID" \
  --name "$NAME" \
  --extra-source "$ROOT/receiver/src/receiver_dev.c" \
  --no-supervisor \
  --define "RECEIVER_PORT=$PORT" \
  --define "TARGET_TITLEID=\"FVTA00002\""
