#!/usr/bin/env bash
# Build the loader (ADR-0016) into a .vpk.
#
#   ./tools/build-loader.sh                 the real loader: FVTA00003, port 1341
#   ./tools/build-loader.sh --scratch       a second one: FVTA00004, port 1342
#
#   --title-id ID   override the slot
#   --port N        override the port
#
# The loader is an ordinary Flutter-Vita application -- same template, same
# build script, same snapshot -- plus one translation unit that owns the port
# and the commands, and minus the crash supervisor. Everything here is either
# the pin check or arguments to tools/build-vita-app.sh.
#
# --scratch exists because replacing FVTA00003 in place is replacing the only
# way to install anything. A scratch loader installs beside the working one,
# on its own port, and can be driven with `./tools/deploy.sh --loader-port 1342`.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"

ENGINE="$ROOT/out/artifacts/loader-engine"
PIN="$ROOT/loader/engine-pin.txt"
TITLE_ID="FVTA00003"
PORT=1341
NAME="Flutter Vita Loader"

while [ $# -gt 0 ]; do
  case "$1" in
    --scratch)  TITLE_ID="FVTA00004"; PORT=1342; NAME="Flutter Loader (scratch)"; shift ;;
    --title-id) TITLE_ID="$2"; shift 2 ;;
    --port)     PORT="$2"; shift 2 ;;
    -h|--help)  sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

# ------------------------------------------------------------- the pin check
#
# ADR-0016 decision 2: the loader links a blessed engine, not the one under
# development, so that a broken engine can cost you your app and never your
# ability to replace it. The sha is what makes that mean anything -- without
# it "the blessed tree" is just a directory someone could have rsynced over.
[ -f "$PIN" ] || {
  echo "No $PIN. Run tools/bless-loader-engine.sh." >&2; exit 1; }
[ -d "$ENGINE" ] || {
  echo "No blessed engine at $ENGINE." >&2
  echo "  It is gitignored, so a fresh checkout has to bless one:" >&2
  echo "    ./tools/bless-loader-engine.sh --reason 'restoring the pin'" >&2
  echo "  Check it produces the sha in $PIN before trusting the result." >&2
  exit 1
}

WANT="$(grep -m1 '^archive_sha256 ' "$PIN" | awk '{print $2}')"
HAVE="$(shasum -a 256 "$ENGINE/lib/libflutter_engine_vita.a" | cut -d' ' -f1)"
if [ "$WANT" != "$HAVE" ]; then
  echo "!! the blessed engine does not match the pin." >&2
  echo "   $PIN says  $WANT" >&2
  echo "   $ENGINE has $HAVE" >&2
  echo >&2
  echo "   Either the tree was overwritten, or the pin should be bumped." >&2
  echo "   Bumping is deliberate: ./tools/bless-loader-engine.sh --reason '...'" >&2
  exit 1
fi
echo "==> pinned engine $(grep -m1 '^flutter ' "$PIN" | awk '{print $2}') ($(echo "$HAVE" | cut -c1-12))"

# --------------------------------------------------------------- build_info
#
# Generated rather than committed: three of the four values are properties of
# the engine artifact, and a committed copy is a copy that can disagree with
# the thing it describes. The fourth is the loader's own version, which comes
# from its pubspec.
key() { grep -m1 "^$1 " "$PIN" | awk '{print $2}'; }
LOADER_VERSION="$(grep -m1 '^version:' "$ROOT/loader/app/pubspec.yaml" | sed 's/^version: *//')"
cat > "$ROOT/loader/app/lib/build_info.dart" <<EOF
// GENERATED by tools/build-loader.sh. Do not edit, and do not commit.
//
// What the screen's bottom line reports. These describe the *pinned* engine
// (ADR-0016 decision 2), which is deliberately not the engine in the tree.
const String kLoaderVersion = '$LOADER_VERSION';
const String kFlutterVersion = '$(key flutter)';
const String kEngineRevision = '$(key engine)';
const String kFrameworkRevision = '$(key framework_rev)';
EOF

echo "==> $NAME [$TITLE_ID] on port $PORT"
exec "$HERE/build-vita-app.sh" "$ROOT/loader/app" \
  --engine "$ENGINE" \
  --title-id "$TITLE_ID" \
  --name "$NAME" \
  --extra-source "$ROOT/loader/src/loader_dev.c" \
  --no-supervisor \
  --define "LOADER_PORT=$PORT" \
  --define "LOADER_TARGET_TITLEID=\"FVTA00002\""
