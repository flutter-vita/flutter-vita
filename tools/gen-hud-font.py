#!/usr/bin/env python3
"""Rasterise the debug strip's font into a C header.

    ./tools/gen-hud-font.py [--preview out.png]

The engine draws its debug strip on the CPU, into the frame the GPU has
finished, and has no text renderer of its own. This bakes RobotoMono
(assets/fonts/RobotoMono-Regular.ttf, Apache 2.0) at two sizes, 10 px for
the labels (6x11 per glyph) and 12 px for the values (8x14), into an alpha
bitmap per glyph, ASCII 0x20..0x7E and the degree sign, and writes
vita_hud_font.h next to vita_embedder.cc. The embedder blends them over the
strip's background.
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, "assets", "fonts", "RobotoMono-Regular.ttf")
OUT = os.path.join(ROOT, "third_party", "flutter", "engine", "src", "flutter",
                   "shell", "platform", "embedder", "vita_hud_font.h")
# (name, px, cell width, cell height, first font row kept)
FONTS = [("Label", 10, 6, 11, 2), ("Value", 12, 8, 14, 3)]
DEGREE = "°"
GLYPHS = [chr(c) for c in range(0x20, 0x7F)] + [DEGREE]


def render(ch, font, w, h, top):
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((0, -top), ch, font=font, fill=255)
    return img


def glyph_name(ch):
    if ch == DEGREE:
        return "degree"
    if ch == " ":
        return "space"
    if ch == "\\":
        return "backslash"
    return ch.replace("*/", "* /")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview")
    args = ap.parse_args()

    lines = [
        "// Generated by tools/gen-hud-font.py; do not edit.",
        "//",
        "// RobotoMono Regular (Apache 2.0), one 8-bit alpha value per pixel, ASCII",
        "// 0x20..0x7E in order, then the degree sign. Two sizes: the strip's labels",
        "// and its values.",
        "#ifndef FLUTTER_SHELL_PLATFORM_EMBEDDER_VITA_HUD_FONT_H_",
        "#define FLUTTER_SHELL_PLATFORM_EMBEDDER_VITA_HUD_FONT_H_",
        "",
        "#include <cstdint>",
        "",
        "namespace {",
        "",
        "constexpr int kHudFontGlyphs = %d;" % len(GLYPHS),
        "constexpr int kHudFontDegree = %d;  // index of the degree sign" % (len(GLYPHS) - 1),
    ]
    sheets = []
    for name, px_size, w, h, top in FONTS:
        font = ImageFont.truetype(FONT, px_size)
        cells = [render(ch, font, w, h, top) for ch in GLYPHS]
        sheets.append((cells, w, h))
        lines += [
            "",
            "// %d px, %dx%d per glyph." % (px_size, w, h),
            "constexpr int kHud%sFontW = %d;" % (name, w),
            "constexpr int kHud%sFontH = %d;" % (name, h),
            "const uint8_t kHud%sFont[kHudFontGlyphs][%d][%d] = {" % (name, h, w),
        ]
        for ch, img in zip(GLYPHS, cells):
            lines.append("    {  // %s" % glyph_name(ch))
            pix = img.load()
            for y in range(h):
                lines.append("        {%s}," % ", ".join("0x%02X" % pix[x, y] for x in range(w)))
            lines.append("    },")
        lines.append("};")
    lines += ["", "}  // namespace", "",
              "#endif  // FLUTTER_SHELL_PLATFORM_EMBEDDER_VITA_HUD_FONT_H_", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d glyphs, %d sizes)" % (os.path.relpath(OUT, ROOT), len(GLYPHS), len(FONTS)))

    if args.preview:
        cols = 32
        rows = (len(GLYPHS) + cols - 1) // cols
        total_h = sum(rows * h for _, _, h in sheets)
        sheet = Image.new("L", (cols * max(w for _, w, _ in sheets), total_h), 0)
        y0 = 0
        for cells, w, h in sheets:
            for i, img in enumerate(cells):
                sheet.paste(img, ((i % cols) * w, y0 + (i // cols) * h))
            y0 += rows * h
        sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(args.preview)
        print("preview %s" % args.preview)


if __name__ == "__main__":
    sys.exit(main())
