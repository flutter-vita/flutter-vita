// The app's Vita plugins, from its resolved packages (ADR-0009).
//
//     dart tools/vita-plugins.dart <package_config.json> <registrant.dart>
//
// Prints the C halves, `vita/plugin.cmake` of each package that has one, as a
// `;` list for the template's VITA_PLUGINS. Writes the Dart halves into a
// generated plugin registrant: each package whose pubspec declares
// flutter.plugin.platforms.vita.dartPluginClass (and an optional `fileName`),
// the shape every Dart platform implementation declares. The registrant is
// written only when its text changes, and removed when no package has a Dart
// half.
//
// tools/build-vita-app.sh runs this. Until 2026-10-16 it was Python inside
// that script; Dart comes with the Flutter SDK the build already uses. Only
// dart: libraries, so it runs as a plain script without a package config, and
// so the pubspec reader below is a small one and not package:yaml.
import 'dart:convert';
import 'dart:io';

/// Python's str.strip(chars) for the two quote characters.
String unquote(String s) {
  var start = 0, end = s.length;
  while (start < end && (s[start] == '"' || s[start] == "'")) {
    start++;
  }
  while (end > start && (s[end - 1] == '"' || s[end - 1] == "'")) {
    end--;
  }
  return s.substring(start, end);
}

/// The scalar at a key path in a pubspec, or null.
///
/// Enough YAML for a pubspec: block mappings by indentation. List items and
/// flow collections are stepped over, comments dropped.
String? yamlValue(String text, List<String> path) {
  final stack = <(int, String)>[];
  for (final raw in const LineSplitter().convert(text)) {
    var line = raw.trimRight();
    if (line.trimLeft().startsWith('#') || line.trim().isEmpty) continue;
    final hash = line.indexOf(' #');
    if (hash >= 0) line = line.substring(0, hash).trimRight();
    final indent = line.length - line.replaceFirst(RegExp(r'^ +'), '').length;
    final body = line.trim();
    if (body.startsWith('- ') || !body.contains(':')) continue;
    final colon = body.indexOf(':');
    final key = unquote(body.substring(0, colon).trim());
    final val = body.substring(colon + 1);
    if (key.isEmpty || (val.isNotEmpty && !val.startsWith(' '))) {
      continue; // `https://...` and friends are values, not keys
    }
    while (stack.isNotEmpty && stack.last.$1 >= indent) {
      stack.removeLast();
    }
    stack.add((indent, key));
    if (stack.length == path.length &&
        List.generate(path.length, (i) => stack[i].$2 == path[i]).every((b) => b)) {
      final v = unquote(val.trim());
      return v.isEmpty ? null : v;
    }
  }
  return null;
}

/// A package's root directory, without a trailing slash.
String packageRoot(String rootUri, String configDir) {
  final path = rootUri.startsWith('file://')
      ? Uri.parse(rootUri).toFilePath()
      : Uri.directory(configDir).resolve(rootUri).toFilePath();
  return path.length > 1 && path.endsWith('/')
      ? path.substring(0, path.length - 1)
      : path;
}

void main(List<String> argv) {
  if (argv.length != 2) {
    stderr.writeln('usage: vita-plugins.dart <package_config.json> <registrant.dart>');
    exit(2);
  }
  final configFile = File(argv[0]);
  final config = jsonDecode(configFile.readAsStringSync()) as Map<String, dynamic>;
  final configDir = configFile.absolute.parent.path;
  final cmake = <String>[];
  final dart = <(String, String, String)>[];
  for (final pkg in (config['packages'] as List? ?? const [])) {
    final root = packageRoot(pkg['rootUri'] as String? ?? '', configDir);
    final pluginCmake = '$root/vita/plugin.cmake';
    if (File(pluginCmake).existsSync()) cmake.add(pluginCmake);
    final pubspec = File('$root/pubspec.yaml');
    if (!pubspec.existsSync()) continue;
    final text = pubspec.readAsStringSync();
    if (!text.contains('dartPluginClass')) continue;
    const path = ['flutter', 'plugin', 'platforms', 'vita'];
    final cls = yamlValue(text, [...path, 'dartPluginClass']);
    if (cls == null) continue;
    final name = pkg['name'] as String;
    final file = yamlValue(text, [...path, 'fileName']) ?? '$name.dart';
    dart.add((name, file, cls));
  }

  final out = File(argv[1]);
  if (dart.isNotEmpty) {
    dart.sort((a, b) {
      var c = a.$1.compareTo(b.$1);
      if (c == 0) c = a.$2.compareTo(b.$2);
      if (c == 0) c = a.$3.compareTo(b.$3);
      return c;
    });
    final lines = [
      "// Generated by tools/build-vita-app.sh from the resolved packages'",
      '// flutter.plugin.platforms.vita.dartPluginClass. Do not edit.',
      '//',
      '// The engine calls _PluginRegistrant.register() at isolate start; each',
      "// call sets the plugin's platform interface to its Vita implementation.",
      '// ignore_for_file: type=lint',
      '',
      for (final (n, f, _) in dart) "import 'package:$n/$f';",
      '',
      "@pragma('vm:entry-point')",
      'class _PluginRegistrant {',
      "  @pragma('vm:entry-point')",
      '  static void register() {',
      for (final (n, _, c) in dart) ...[
        '    try {',
        '      $c.registerWith();',
        '    } catch (err) {',
        "      print('`$n` threw an error: \$err. The app may not function "
            "as expected until you remove this plugin from pubspec.yaml');",
        '    }',
      ],
      '  }',
      '}',
      '',
    ];
    final text = lines.join('\n');
    if (!(out.existsSync() && out.readAsStringSync() == text)) {
      out.writeAsStringSync(text);
    }
  } else if (out.existsSync()) {
    out.deleteSync();
  }
  stdout.writeln(cmake.join(';'));
}
