#!/usr/bin/env python3
"""Generate engine/gles2/src/stubs.c and engine/gles2/src/procs.c.

    ./tools/gles2-gen.py

stubs.c: every GLES 2.0 entry point (from the SDK's GLES2/gl2.h) that no file
in engine/gles2/src defines gets a recording stub: it sets GL_INVALID_OPERATION and
writes its name to ux0:data/flutter-vita/gles2-unimplemented.txt the first
time it is called. That file is how an app says which function it needs.

procs.c: the name -> pointer table behind fvgl_get_proc_address, over every
entry point in gl2.h plus the GL_OES/EXT names Skia asks for by name.

Run it after adding or removing GL functions in engine/gles2/src; commit the output.
"""
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "engine" / "gles2" / "src"
GL2 = Path(os.environ.get("VITASDK", os.path.expanduser("~/vitasdk"))) / "arm-vita-eabi/include/GLES2/gl2.h"

PROTO = re.compile(r"GL_APICALL\s+([\w\s\*]+?)\s*GL_APIENTRY\s+(gl\w+)\s*\((.*?)\);", re.S)
DEF = re.compile(r"GL_APIENTRY\s+((?:gl|egl)\w+)\s*\(")

# Extension names Skia binds by name. A name maps to the core function that
# does the job; None means "the function of this name, if engine/gles2/src
# defines one, and a stub of its own otherwise".
ALIASES = {
    "glGenVertexArraysOES": None, "glBindVertexArrayOES": None, "glDeleteVertexArraysOES": None,
    "glMapBufferOES": None, "glUnmapBufferOES": None, "glFlushMappedBufferRangeEXT": None,
    "glMapBufferRangeEXT": None, "glGetProgramBinaryOES": None, "glProgramBinaryOES": None,
    "glDrawArraysInstancedEXT": None, "glDrawElementsInstancedEXT": None, "glVertexAttribDivisorEXT": None,
    "glPushGroupMarkerEXT": None, "glPopGroupMarkerEXT": None, "glInsertEventMarkerEXT": None,
    "glGetStringi": None, "glDiscardFramebufferEXT": None, "glBlitFramebufferANGLE": None,
    "glRenderbufferStorageMultisampleEXT": None, "glTexStorage2DEXT": None,
    "glBindUniformLocationCHROMIUM": None, "glCopyTextureCHROMIUM": None,
    "glGenQueriesEXT": None, "glDeleteQueriesEXT": None, "glBeginQueryEXT": None, "glEndQueryEXT": None,
    "glGetQueryObjectuivEXT": None, "glGetQueryObjectivEXT": None, "glQueryCounterEXT": None,
    "glGetQueryObjectui64vEXT": None, "glGetQueryObjecti64vEXT": None, "glGetQueryivEXT": None,
    "glFenceSyncAPPLE": None, "glClientWaitSyncAPPLE": None, "glDeleteSyncAPPLE": None, "glWaitSyncAPPLE": None,
    "glIsSyncAPPLE": None, "glEGLImageTargetTexture2DOES": None, "glEGLImageTargetRenderbufferStorageOES": None,
    "glBlendBarrierKHR": None, "glBlendBarrierNV": None, "glGetTexLevelParameterivANGLE": None,
    "glTexImage2DMultisampleANGLE": None, "glGetMultisamplefvANGLE": None, "glSampleMaskiANGLE": None,
    "glMinSampleShadingOES": None, "glWindowRectanglesEXT": None, "glCoverageModulationCHROMIUM": None,
    "glPolygonModeNV": None, "glBindFragDataLocationEXT": None, "glBindFragDataLocationIndexedEXT": None,
    "glMemoryBarrierEXT": None, "glMemoryBarrierByRegionEXT": None, "glBindImageTextureEXT": None,
    "glDrawRangeElementsEXT": None, "glTexBufferEXT": None, "glTexBufferRangeEXT": None,
    "glBindBufferBaseEXT": None, "glBindBufferRangeEXT": None, "glGetUniformBlockIndexEXT": None,
    "glUniformBlockBindingEXT": None, "glGetActiveUniformBlockivEXT": None, "glGetActiveUniformBlockNameEXT": None,
    "glGetUniformIndicesEXT": None, "glGetActiveUniformsivEXT": None,
    "glGetFramebufferAttachmentParameteriv": "glGetFramebufferAttachmentParameteriv",
    "eglQueryString": None,
}


def prototypes():
    text = GL2.read_text()
    protos = []
    for ret, name, params in PROTO.findall(text):
        params = " ".join(params.split())
        protos.append((ret.strip(), name, params))
    return protos


def implemented():
    names = set()
    for c in SRC.glob("*.c"):
        if c.name in ("stubs.c", "procs.c"):
            continue
        names.update(DEF.findall(c.read_text()))
    return names


def param_names(params):
    if params in ("", "void"):
        return []
    out = []
    for p in params.split(","):
        p = p.strip().rstrip("]")
        p = re.sub(r"\[.*$", "", p)
        out.append(p.split()[-1].lstrip("*"))
    return out


def main():
    protos = prototypes()
    have = implemented()
    stubs = [p for p in protos if p[1] not in have]

    lines = [
        "// Generated by tools/gles2-gen.py. Do not edit; add the function to a",
        "// source file in engine/gles2/src and run the generator again.",
        "//",
        "// Recording stubs: GLES 2.0 entry points nothing here implements yet. Each",
        "// sets GL_INVALID_OPERATION and, once, writes its name to",
        "// ux0:data/flutter-vita/gles2-unimplemented.txt, so the app that needs it",
        "// says so on the card and the gap has a name.",
        "#include \"fvgl_internal.h\"",
        "",
        "#define FVGL_STUB(name) fvgl_stub_called(#name)",
        "",
    ]
    for ret, name, params in stubs:
        args = param_names(params)
        lines.append(f"GL_APICALL {ret} GL_APIENTRY {name}({params}) {{")
        for a in args:
            lines.append(f"  (void){a};")
        lines.append(f"  FVGL_STUB({name});")
        if ret != "void":
            lines.append("  return 0;")
        lines.append("}")
        lines.append("")
    # Extension names Skia may ask for and nothing here defines: one shared
    # stub each, void(void) ABI.
    for name, target in sorted(ALIASES.items()):
        if target is not None or name in have:
            continue
        lines.append(f"void {name}_stub(void) {{ FVGL_STUB({name}); }}")
    (SRC / "stubs.c").write_text("\n".join(lines) + "\n")

    lines = [
        "// Generated by tools/gles2-gen.py. Do not edit.",
        "//",
        "// The name -> pointer table behind fvgl_get_proc_address: every GLES 2.0",
        "// entry point, real or stub, plus the extension names Skia asks for.",
        "#include <string.h>",
        "",
        "#include \"fvgl_internal.h\"",
        "",
    ]
    for name, target in sorted(ALIASES.items()):
        if target is None and name not in have:
            lines.append(f"void {name}_stub(void);")
    lines.append("")
    lines.append("static const struct { const char* name; void* fn; } kProcs[] = {")
    for _, name, _ in protos:
        lines.append(f"  {{\"{name}\", (void*){name}}},")
    for name, target in sorted(ALIASES.items()):
        if target is None:
            suffix = "" if name in have else "_stub"
            lines.append(f"  {{\"{name}\", (void*){name}{suffix}}},")
        elif target != name:
            lines.append(f"  {{\"{name}\", (void*){target}}},")
    lines.append("};")
    lines.append("")
    lines.append("void* fvgl_get_proc_address(const char* name) {")
    lines.append("  if (!name) return NULL;")
    lines.append("  for (size_t i = 0; i < sizeof kProcs / sizeof kProcs[0]; i++) {")
    lines.append("    if (strcmp(kProcs[i].name, name) == 0) return kProcs[i].fn;")
    lines.append("  }")
    lines.append("  fvgl_log(\"GetProcAddress: no %s\", name);")
    lines.append("  return NULL;")
    lines.append("}")
    (SRC / "procs.c").write_text("\n".join(lines) + "\n")
    print(f"{len(protos)} entry points, {len(protos) - len(stubs)} real, {len(stubs)} stubs")


if __name__ == "__main__":
    main()
